function equities(
  rows: CatalogRow[],
  region: "KR" | "US",
  instrumentType: "stock" | "etf",
): InstrumentDefinition[] {
  return rows.map(([symbol, label, sector]) => ({
    id: `asset-${symbol}`,
    symbol,
    label,
    sector,
    region,
    instrumentType,
    assetClass: "equity",
    currency: region === "KR" ? "KRW" : "USD",
    provider: "yahoo",
  }));
}

