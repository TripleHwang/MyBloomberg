export function collectionInstruments(
  watchlist: InstrumentDefinition[],
): InstrumentDefinition[] {
  const definitions = new Map(
    [...coreInstruments, ...explorationInstruments].map((instrument) => [
      instrument.symbol,
      instrument,
    ]),
  );
  for (const item of watchlist)
    definitions.set(item.symbol, {
      ...item,
      ...definitions.get(item.symbol),
      isWatchlist: true,
    });
  return [...definitions.values()];
}
